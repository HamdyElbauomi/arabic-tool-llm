import json
from collections import Counter, defaultdict
from difflib import SequenceMatcher
from pathlib import Path


# --------------------------------------------------
# Project paths
# --------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

RESULTS_PATH = (
    PROJECT_ROOT
    / "data"
    / "benchmark"
    / "post_training_comparison.json"
)

ERROR_REPORT_PATH = (
    PROJECT_ROOT
    / "data"
    / "benchmark"
    / "error_analysis.json"
)


# --------------------------------------------------
# Load evaluation results
# --------------------------------------------------

def load_results() -> dict:
    """
    Load the results generated by post_training.py.
    """

    with open(
        RESULTS_PATH,
        "r",
        encoding="utf-8",
    ) as file:

        return json.load(file)


# --------------------------------------------------
# Text similarity
# --------------------------------------------------

def text_similarity(
    expected_value,
    predicted_value,
) -> float:
    """
    Calculate simple similarity between two string values.

    This does NOT change the official metric.
    It only helps us understand whether two different
    strings may still have similar meaning/form.
    """

    if not isinstance(expected_value, str):
        return 0.0

    if not isinstance(predicted_value, str):
        return 0.0

    expected_text = expected_value.lower().strip()
    predicted_text = predicted_value.lower().strip()

    return SequenceMatcher(
        None,
        expected_text,
        predicted_text,
    ).ratio()


# --------------------------------------------------
# Analyze arguments
# --------------------------------------------------

def analyze_arguments(
    expected_arguments: dict,
    predicted_arguments: dict,
) -> dict:

    missing_arguments = []
    extra_arguments = []
    wrong_values = []
    possible_text_variations = []

    # Check expected arguments
    for key, expected_value in expected_arguments.items():

        if key not in predicted_arguments:
            missing_arguments.append(key)
            continue

        predicted_value = predicted_arguments[key]

        if predicted_value != expected_value:

            wrong_value = {
                "argument": key,
                "expected": expected_value,
                "predicted": predicted_value,
            }

            wrong_values.append(
                wrong_value
            )

            similarity = text_similarity(
                expected_value,
                predicted_value,
            )

            # Only a diagnostic hint.
            # We still count the argument as incorrect.
            if similarity >= 0.75:

                possible_text_variations.append(
                    {
                        "argument": key,
                        "expected": expected_value,
                        "predicted": predicted_value,
                        "similarity": round(
                            similarity,
                            3,
                        ),
                    }
                )

    # Check unexpected arguments
    for key in predicted_arguments:

        if key not in expected_arguments:
            extra_arguments.append(key)

    return {
        "missing_arguments": missing_arguments,
        "extra_arguments": extra_arguments,
        "wrong_values": wrong_values,
        "possible_text_variations": (
            possible_text_variations
        ),
    }


# --------------------------------------------------
# Analyze one prediction
# --------------------------------------------------

def analyze_prediction(
    example: dict,
) -> dict:

    expected = example["expected"]
    prediction = example["prediction"]

    # ----------------------------------------------
    # Invalid JSON / structure
    # ----------------------------------------------

    if prediction is None:

        return {
            "error_type": "invalid_json",
            "details": {
                "raw_response": example[
                    "raw_response"
                ]
            },
        }

    # ----------------------------------------------
    # Wrong tool
    # ----------------------------------------------

    if prediction["tool"] != expected["tool"]:

        return {
            "error_type": "wrong_tool",
            "details": {
                "expected_tool": expected["tool"],
                "predicted_tool": prediction["tool"],
            },
        }

    # ----------------------------------------------
    # Correct tool → analyze arguments
    # ----------------------------------------------

    argument_analysis = analyze_arguments(
        expected_arguments=expected[
            "arguments"
        ],
        predicted_arguments=prediction[
            "arguments"
        ],
    )

    if argument_analysis[
        "missing_arguments"
    ]:

        return {
            "error_type": "missing_argument",
            "details": argument_analysis,
        }

    if argument_analysis[
        "extra_arguments"
    ]:

        return {
            "error_type": "extra_argument",
            "details": argument_analysis,
        }

    if argument_analysis[
        "wrong_values"
    ]:

        return {
            "error_type": "wrong_argument_value",
            "details": argument_analysis,
        }

    return {
        "error_type": "correct",
        "details": {},
    }


# --------------------------------------------------
# Compare base vs fine-tuned
# --------------------------------------------------

def compare_models(
    base_example: dict,
    tuned_example: dict,
) -> str:
    """
    Determine whether fine-tuning improved or hurt
    this individual example.
    """

    base_correct = (
        base_example["metrics"][
            "exact_match"
        ]
    )

    tuned_correct = (
        tuned_example["metrics"][
            "exact_match"
        ]
    )

    if not base_correct and tuned_correct:
        return "improved"

    if base_correct and not tuned_correct:
        return "regressed"

    if base_correct and tuned_correct:
        return "correct_in_both"

    return "wrong_in_both"


# --------------------------------------------------
# Main
# --------------------------------------------------

def main() -> None:

    print("=" * 65)
    print("ERROR ANALYSIS")
    print("=" * 65)

    results = load_results()

    base_predictions = results[
        "base"
    ]["predictions"]

    tuned_predictions = results[
        "fine_tuned"
    ]["predictions"]

    base_by_id = {
        example["id"]: example
        for example in base_predictions
    }

    error_counts = Counter()
    comparison_counts = Counter()

    errors_by_tool = defaultdict(
        Counter
    )

    detailed_errors = []

    # --------------------------------------------------
    # Analyze fine-tuned predictions
    # --------------------------------------------------

    for tuned_example in tuned_predictions:

        example_id = tuned_example["id"]

        base_example = base_by_id[
            example_id
        ]

        analysis = analyze_prediction(
            tuned_example
        )

        comparison = compare_models(
            base_example,
            tuned_example,
        )

        error_type = analysis[
            "error_type"
        ]

        expected_tool = tuned_example[
            "expected"
        ]["tool"]

        error_counts[
            error_type
        ] += 1

        comparison_counts[
            comparison
        ] += 1

        errors_by_tool[
            expected_tool
        ][error_type] += 1

        if error_type != "correct":

            detailed_errors.append(
                {
                    "id": example_id,
                    "input": tuned_example[
                        "input"
                    ],
                    "expected": tuned_example[
                        "expected"
                    ],
                    "prediction": tuned_example[
                        "prediction"
                    ],
                    "raw_response": tuned_example[
                        "raw_response"
                    ],
                    "error_type": error_type,
                    "details": analysis[
                        "details"
                    ],
                    "base_vs_tuned": (
                        comparison
                    ),
                }
            )

    # --------------------------------------------------
    # Build report
    # --------------------------------------------------

    report = {
        "total_examples": len(
            tuned_predictions
        ),
        "error_counts": dict(
            error_counts
        ),
        "base_vs_fine_tuned": dict(
            comparison_counts
        ),
        "errors_by_tool": {
            tool: dict(counts)
            for tool, counts
            in errors_by_tool.items()
        },
        "detailed_errors": (
            detailed_errors
        ),
    }

    # --------------------------------------------------
    # Save report
    # --------------------------------------------------

    with open(
        ERROR_REPORT_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            report,
            file,
            ensure_ascii=False,
            indent=2,
        )

    # --------------------------------------------------
    # Print summary
    # --------------------------------------------------

    print(
        f"\nTotal examples: "
        f"{len(tuned_predictions)}"
    )

    print("\nERROR TYPES")
    print("-" * 40)

    for error_type, count in (
        error_counts.items()
    ):

        print(
            f"{error_type:<25} {count}"
        )

    print("\nBASE VS FINE-TUNED")
    print("-" * 40)

    for status, count in (
        comparison_counts.items()
    ):

        print(
            f"{status:<25} {count}"
        )

    print("\nDETAILED ERRORS")
    print("-" * 65)

    for error in detailed_errors:

        print(
            f"\nID: {error['id']}"
        )

        print(
            f"Input: {error['input']}"
        )

        print(
            f"Error: "
            f"{error['error_type']}"
        )

        print(
            f"Expected: "
            f"{error['expected']}"
        )

        print(
            f"Predicted: "
            f"{error['prediction']}"
        )

        print(
            f"Base vs Tuned: "
            f"{error['base_vs_tuned']}"
        )

        text_variations = (
            error["details"].get(
                "possible_text_variations",
                [],
            )
        )

        if text_variations:

            print(
                "Possible semantic/text "
                "variation:"
            )

            for variation in (
                text_variations
            ):

                print(
                    f"  {variation}"
                )

    print("\n" + "=" * 65)

    print(
        "✅ Error analysis completed."
    )

    print(
        f"Report saved to:\n"
        f"{ERROR_REPORT_PATH}"
    )


if __name__ == "__main__":
    main()